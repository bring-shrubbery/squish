#!/bin/bash
# Prints the Homebrew formula for the squish CLI release: prebuilt binaries for macOS and
# Linux, arm64 and x86_64, from the cli-v<version> GitHub release. The release workflow
# commits it to the tap as Formula/squish.rb.
#
#   release-cli-formula.sh --version 0.0.1 --repo bring-shrubbery/squish --sha-dir dist/cli
#
# --sha-dir holds squish-<version>-<target>.tar.gz.sha256 for every target, each starting
# with the hex digest (shasum's format). A missing or malformed digest is an error.
set -euo pipefail

version="" repo="" sha_dir=""
while [ $# -gt 0 ]; do
    case "$1" in
        --version) version=$2; shift 2 ;;
        --repo) repo=$2; shift 2 ;;
        --sha-dir) sha_dir=$2; shift 2 ;;
        *) echo "usage: release-cli-formula.sh --version X.Y.Z --repo owner/name --sha-dir DIR" >&2; exit 1 ;;
    esac
done
if ! [[ "$version" =~ ^[0-9]+\.[0-9]+\.[0-9]+$ ]] || [ -z "$repo" ] || [ ! -d "$sha_dir" ]; then
    echo "usage: release-cli-formula.sh --version X.Y.Z --repo owner/name --sha-dir DIR" >&2
    exit 1
fi

# The digest for a target, or exit with an error.
sha() {
    local file="$sha_dir/squish-$version-$1.tar.gz.sha256" digest
    if [ ! -f "$file" ]; then
        echo "error: no digest for $1 ($file)" >&2; exit 1
    fi
    digest=$(awk '{print $1; exit}' "$file")
    if ! [[ "$digest" =~ ^[0-9a-f]{64}$ ]]; then
        echo "error: $file does not start with a sha256 digest" >&2; exit 1
    fi
    echo "$digest"
}

mac_arm=$(sha aarch64-apple-darwin)
mac_intel=$(sha x86_64-apple-darwin)
linux_arm=$(sha aarch64-unknown-linux-musl)
linux_intel=$(sha x86_64-unknown-linux-musl)
base="https://github.com/$repo/releases/download/cli-v$version/squish-$version"

cat <<EOF
# Generated by scripts/release-cli-formula.sh in $repo for cli-v$version; edits are overwritten.
class Squish < Formula
  desc "Find and safely clean up the git worktrees your coding agents leave behind"
  homepage "https://github.com/$repo/tree/main/cli"
  version "$version"
  license "Apache-2.0"

  on_macos do
    on_arm do
      url "$base-aarch64-apple-darwin.tar.gz"
      sha256 "$mac_arm"
    end
    on_intel do
      url "$base-x86_64-apple-darwin.tar.gz"
      sha256 "$mac_intel"
    end
  end

  on_linux do
    on_arm do
      url "$base-aarch64-unknown-linux-musl.tar.gz"
      sha256 "$linux_arm"
    end
    on_intel do
      url "$base-x86_64-unknown-linux-musl.tar.gz"
      sha256 "$linux_intel"
    end
  end

  def install
    bin.install "squish"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/squish --version")
    system "git", "init", "--quiet", testpath/"repo"
    assert_match "1 repo", shell_output("#{bin}/squish analyze #{testpath} --color never")
  end
end
EOF
